#!/usr/bin/env python3
"""Build deterministic, language-specific Zotero XPIs without dependencies."""
import argparse
import hashlib
import html
import json
import re
import subprocess
from pathlib import Path
from urllib.parse import urlparse
from zipfile import ZipFile, ZipInfo, ZIP_DEFLATED
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'src'
DIST = ROOT / 'dist'
REPOSITORY = 'Hanson-Wang-chn/zotero-keep-reader-ready'
LOCALES = ('en-US', 'zh-CN')

def validate_manifest(manifest):
    app = manifest.get('applications', {}).get('zotero', {})
    for key in ('id', 'update_url', 'strict_max_version'):
        if not app.get(key):
            raise ValueError('applications.zotero.' + key + ' not provided')
    url = urlparse(app['update_url'])
    if url.scheme != 'https' or not url.hostname:
        raise ValueError('update_url must be an absolute HTTPS URL')
    if app.get('strict_min_version') != '10.0.6' or app['strict_max_version'] != '10.0.*':
        raise ValueError('Unexpected Zotero compatibility range')
    if manifest.get('manifest_version') != 2:
        raise ValueError('Expected manifest_version 2')

def write_archive(path, entries):
    with ZipFile(path, 'w', compression=ZIP_DEFLATED, compresslevel=9) as archive:
        for name, data in sorted(entries.items()):
            info = ZipInfo(name, (2026, 10, 23, 0, 0, 0))
            info.compress_type = ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, data)
    with ZipFile(path) as archive:
        if archive.testzip() is not None:
            raise ValueError('Archive failed CRC check')

def read_catalog(locale):
    return json.loads((ROOT / 'locales' / (locale + '.json')).read_text(encoding='utf-8'))

def render_xhtml(template, catalog):
    return re.sub(r'\{\{([A-Za-z]+)\}\}',
                  lambda match: html.escape(catalog[match[1]], quote=True), template)

def build(locale):
    catalog = read_catalog(locale)
    manifest = json.loads((SOURCE / 'manifest.json').read_text(encoding='utf-8'))
    manifest['name'] = catalog['pluginName']
    manifest['description'] = catalog['manifestDescription']
    manifest['applications']['zotero']['update_url'] = (
        f'https://raw.githubusercontent.com/{REPOSITORY}/main/updates/{locale}.json')
    validate_manifest(manifest)
    entries = {p.name: p.read_bytes() for p in SOURCE.iterdir() if p.is_file()}
    entries['manifest.json'] = (json.dumps(manifest, ensure_ascii=False, indent=2) + '\n').encode()
    xhtml = render_xhtml((SOURCE / 'preferences.xhtml').read_text(encoding='utf-8'), catalog)
    ET.fromstring(xhtml)
    entries['preferences.xhtml'] = xhtml.encode()
    data = {'locale': locale, 'strings': catalog}
    entries['locale-data.js'] = ('/* Generated by build.py; SPDX-License-Identifier: MIT */\n'
        + 'var KeepReaderReadyLocaleData = ' + json.dumps(data, ensure_ascii=False) + ';\n').encode()
    for name in ('README.md', 'README.zh-CN.md', 'CHANGELOG.md', 'LICENSE'):
        entries[name] = (ROOT / name).read_bytes()
    result = DIST / f'keep-reader-ready-{manifest["version"]}-{locale}.xpi'
    write_archive(result, entries)
    return result

def build_source(version):
    excluded = {'.git', 'dist', '__pycache__', 'research', 'node_modules', 'bootstrap'}
    entries = {}
    for p in ROOT.rglob('*'):
        rel = p.relative_to(ROOT)
        if p.is_file() and not p.is_symlink() and not any(x in excluded for x in rel.parts):
            if p.name.endswith('.pyc') or p.name == '.DS_Store':
                continue
            entries['keep-reader-ready/' + rel.as_posix()] = p.read_bytes()
    result = DIST / f'keep-reader-ready-{version}-source.zip'
    write_archive(result, entries)
    return result

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--locale', choices=(*LOCALES, 'all'), default='all')
    args = parser.parse_args()
    catalogs = [read_catalog(locale) for locale in LOCALES]
    if set(catalogs[0]) != set(catalogs[1]):
        raise ValueError('Translation catalogs must contain the same keys')
    for key in catalogs[0]:
        if set(re.findall(r'\{([A-Za-z]+)\}', catalogs[0][key])) != set(re.findall(r'\{([A-Za-z]+)\}', catalogs[1][key])):
            raise ValueError('Translation parameters differ: ' + key)
    ET.parse(SOURCE / 'icon.svg')
    for p in sorted(SOURCE.glob('*.js')):
        subprocess.run(['node', '--check', str(p)], check=True)
    DIST.mkdir(exist_ok=True)
    locales = LOCALES if args.locale == 'all' else (args.locale,)
    files = [build(locale) for locale in locales]
    version = json.loads((SOURCE / 'manifest.json').read_text())['version']
    files.append(build_source(version))
    sums = [(hashlib.sha256(p.read_bytes()).hexdigest(), p.name) for p in files]
    (DIST / 'SHA256SUMS.txt').write_text(''.join(f'{digest}  {name}\n' for digest, name in sums))
    print(json.dumps({'version': version, 'files': [p.name for p in files]}))

if __name__ == '__main__':
    main()
